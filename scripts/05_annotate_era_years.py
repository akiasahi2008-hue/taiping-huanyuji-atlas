# 漢数字 -> 整数変換 (元=1, 一〜九十九)
KANJI_DIGITS = {
    "一": 1, "二": 2, "三": 3, "四": 4, "五": 5,
    "六": 6, "七": 7, "八": 8, "九": 9,
}


def parse_kanji_year(s: str) -> int | None:
    if s in ("元", "初"):
        return 1
    if not s:
        return None
    total = 0
    if "十" in s:
        parts = s.split("十")
        tens = 1 if parts[0] == "" else KANJI_DIGITS.get(parts[0], 0)
        ones = 0 if parts[1] == "" else KANJI_DIGITS.get(parts[1], 0)
        if tens == 0 and parts[0] != "":
            return None
        total = tens * 10 + ones
    else:
        if len(s) == 1 and s in KANJI_DIGITS:
            total = KANJI_DIGITS[s]
        else:
            return None
    return total if 1 <= total <= 75 else None


def format_ce_year(start_year: int, offset: int) -> str:
    """
    start_year: 元年の西暦 (紀元前は負数、例: 前140年 = -140, 西暦668年 = 668)
    offset: 年数 (元年=1, 二年=2 ...)
    """
    if start_year < 0:
        ce = start_year + (offset - 1)
        if ce < 0:
            return f"前{-ce}年"
        else:
            return f"{ce + 1}年"
    else:
        ce = start_year + (offset - 1)
        return f"{ce}年"


def format_ce_range(start_year: int, span: int) -> str:
    s = format_ce_year(start_year, 1)
    if span <= 1:
        return s
    e = format_ce_year(start_year, span)
    if not s.startswith("前") and not e.startswith("前"):
        return f"{s[:-1]}〜{e}"
    return f"{s}〜{e}"


