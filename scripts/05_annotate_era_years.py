# 長い元号名から優先マッチさせる正規表現パターンを構築
ALL_ERA_KEYS = sorted(
    set(UNAMBIGUOUS_ERAS.keys())
    | {
        "太和", "大和", "上元", "天宝", "天寶", "泰始", "太始",
        "永安", "永平", "永和", "建武", "甘露", "永初", "永元",
        "建元", "建興", "太平", "乾徳", "至徳", "元和", "元康",
        "和平", "永泰", "永昌", "延和", "明帝",
    },
    key=len,
    reverse=True,
)

# 1) 「元号＋年数（元年〜数十年/載）」または「元号＋の初め/初年/年間/年中」
ERA_MAIN_PATTERN = re.compile(
    r"(" + "|".join(re.escape(k) for k in ALL_ERA_KEYS) + r")"
    r"(?:(元|[一二三四五六七八九十]{1,3})(年|載)|(の初め|初年|年間|年中))"
    r"(?:（(?:前)?\d+(?:〜(?:前)?\d+)?年）)?"
)


def annotate_text(text: str) -> tuple[str, int]:
    if not text or not isinstance(text, str):
        return text, 0

    # 既存の括弧付き西暦があれば一旦除去して冪等性を確保
    cleaned = re.sub(
        r"(" + "|".join(re.escape(k) for k in ALL_ERA_KEYS) + r")"
        r"(?:(?:元|[一二三四五六七八九十]{1,3})(?:年|載)|(?:の初め|初年|年間|年中))"
        r"\K（(?:前)?\d+(?:〜(?:前)?\d+)?年）",
        "",
        text,
    ) if False else text

    count = 0

    def _repl(m: re.Match) -> str:
        nonlocal count
        era = m.group(1)
        num_str = m.group(2)
        unit = m.group(3)
        period_suffix = m.group(4)

        start_pos = m.start()
        left_ctx = text[max(0, start_pos - 120):start_pos]

        if num_str:
            yr = parse_kanji_year(num_str)
            if yr is None:
                return m.group(0)
            res = resolve_era_start(era, yr, left_ctx)
            if res is None:
                return m.group(0)
            start_year, max_yr = res
            if yr > max_yr + 2:
                return m.group(0)
            ce_str = format_ce_year(start_year, yr)
            count += 1
            return f"{era}{num_str}{unit}（{ce_str}）"
        else:
            # の初め / 初年 / 年間 / 年中
            if era in ("隠公", "桓公", "荘公", "莊公", "閔公", "僖公", "文公", "宣公", "成公", "襄公", "昭公", "定公", "哀公", "始皇", "始皇帝", "二世", "高帝", "高祖", "高后", "文帝", "景帝", "廃帝", "恭帝", "閔帝", "明帝"):
                return m.group(0)
            res = resolve_era_start(era, 1, left_ctx)
            if res is None:
                return m.group(0)
            start_year, max_yr = res
            if period_suffix in ("の初め", "初年"):
                ce_str = format_ce_year(start_year, 1)
                count += 1
                return f"{era}{period_suffix}（{ce_str}）"
            else:
                ce_range = format_ce_range(start_year, max_yr)
                count += 1
                return f"{era}{period_suffix}（{ce_range}）"

    new_text = ERA_MAIN_PATTERN.sub(_repl, text)
    return new_text, count


def main():
    total_replaced = 0
    files_and_fields = [
        ("taiping_huanyuji_prefectures.json", ["history_ja", "customs_ja", "surnames_ja", "figures_ja"]),
        ("taiping_huanyuji_counties.json", ["intro_ja"]),
        ("taiping_huanyuji_landmarks.json", ["desc_ja"]),
        ("taiping_huanyuji_siyi.json", ["history_ja", "sizhi_ja", "customs_ja"]),
    ]

    for fname, fields in files_and_fields:
        fpath = DATA_DIR / fname
        data = json.loads(fpath.read_text(encoding="utf-8"))
        file_cnt = 0
        for item in data:
            for fld in fields:
                val = item.get(fld)
                if isinstance(val, str) and val:
                    new_val, c = annotate_text(val)
                    item[fld] = new_val
                    file_cnt += c
                elif isinstance(val, list):
                    new_list = []
                    for s in val:
                        if isinstance(s, str) and s:
                            ns, c = annotate_text(s)
                            new_list.append(ns)
                            file_cnt += c
                        else:
                            new_list.append(s)
                    item[fld] = new_list
        fpath.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"Annotated {fname}: {file_cnt:,} era-year occurrences updated.")
        total_replaced += file_cnt

    print(f"Total era-year annotations added: {total_replaced:,}")


if __name__ == "__main__":
    main()
